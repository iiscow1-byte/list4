/** Look one string up. Falls back to the English it was keyed by. */
export function translate(locale: string, text: string): string {
  return MESSAGES[locale as LocaleCode]?.[text] ?? text
}

/**
 * The best match for a browser's `Accept-Language`, or null.
 *
 * Exact code first, then the base language — `pt` and `pt-PT` both land on
 * `pt-BR`, which is the Portuguese this community actually speaks, and any
 * `zh` lands on Simplified. A wrong-but-close language beats English for a
 * reader who cannot read English, and they can always change it.
 */
export function matchLocale(header: string | undefined | null): LocaleCode | null {
  if (!header) return null
  const wanted = header.split(',')
    .map((part) => part.split(';')[0]!.trim())
    .filter(Boolean)
  for (const w of wanted) {
    if (LOCALE_CODES.has(w)) return w as LocaleCode
    const base = w.split('-')[0]!.toLowerCase()
    const hit = LOCALES.find((l) => l.code.split('-')[0] === base)
    if (hit) return hit.code
  }
  return null
}
