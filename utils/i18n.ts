/**
 * The site, in other languages.
 *
 * ## What is translated, and what deliberately isn't
 *
 * The site's *chrome* — navigation, headings, buttons, the words the site says
 * about itself. Not the content: level names, creator names, comments, bios,
 * list titles and the changelog are written by people, in whatever language
 * they chose, and machine-shuffling them between languages would make them
 * wrong rather than accessible. A Spanish reader wants "Clasificación" for the
 * leaderboard heading and still wants the level called "Bloodbath".
 *
 * Difficulty names, tier names and rating names are also left alone: they are
 * the game's own vocabulary and the community uses the English terms in every
 * language.
 *
 * ## English is the key
 *
 * A message is looked up by its English text rather than by an invented id like
 * `nav.build.label`. Retrofitting ids onto a site this size means touching every
 * string twice and keeping a second file in sync with the first; using the
 * source text means an untranslated string renders as English instead of as
 * `nav.build.label`, which is the correct failure. It also means adding a new
 * language is one object, and adding a new string to the UI is nothing at all
 * until somebody translates it.
 *
 * The cost is that changing an English string orphans its translations. That is
 * the right trade here: the alternative orphans them silently, as a key that
 * still resolves to text nobody updated.
 */

